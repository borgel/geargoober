// Generates a Fusion 360 Python script that creates/updates User Parameters and a shaft layout sketch.
import type { Project } from '../model';
import type { Solution } from '../solver';

/** Fusion parameter names must be identifiers. */
export function paramName(id: string): string {
  const s = id.replace(/[^A-Za-z0-9_]/g, '_');
  return /^[A-Za-z_]/.test(s) ? s : `p_${s}`;
}

const num = (x: number) => {
  const s = x.toFixed(6).replace(/\.?0+$/, '');
  return s === '-0' ? '0' : s;
};
const py = (s: string) => JSON.stringify(s); // JSON strings are valid Python string literals

export function fusionScript(p: Project, s: Solution, version: string): string {
  const params: [string, string, string, string][] = [
    ['gt_module', `${num(s.module)} mm`, 'mm', 'gear module'],
    ['gt_pa', `${num(p.pressureAngleDeg)} deg`, 'deg', 'pressure angle'],
  ];
  for (const sh of s.shafts) {
    params.push([`${paramName(sh.id)}_x`, `${num(sh.x)} mm`, 'mm', `shaft ${sh.id} x`]);
    params.push([`${paramName(sh.id)}_y`, `${num(sh.y)} mm`, 'mm', `shaft ${sh.id} y`]);
  }
  for (const m of s.meshes) {
    params.push([`cd_${paramName(m.a)}_${paramName(m.b)}`, `${num(m.centerDist)} mm`, 'mm', `center distance ${m.a}-${m.b}`]);
  }
  for (const g of p.gears) params.push([`${paramName(g.id)}_face`, `${num(g.faceWidth)} mm`, 'mm', `${g.id} face width`]);
  for (const r of p.racks) params.push([`${paramName(r.id)}_face`, `${num(r.faceWidth)} mm`, 'mm', `${r.id} face width`]);

  const gearShaft = new Map(s.gears.map((g) => [g.id, g.shaftId]));
  const links = s.meshes
    .filter((m) => gearShaft.has(m.b))
    .map((m) => [gearShaft.get(m.a)!, gearShaft.get(m.b)!] as const);

  const comment = p.name.replace(/[\r\n]+/g, ' ');
  return `# GearGoober -> Fusion 360 parameter script
# Project: ${comment}
# Generated by GearGoober ${version}
#
# Run from Utilities > Add-Ins > Scripts and Add-Ins (+ next to My Scripts).
# Creates or updates User Parameters and a "GearTrain Layout" sketch with one point per shaft.
# Re-running moves the existing tagged points instead of recreating them, so geometry you
# constrained to them stays attached.
import adsk.core, adsk.fusion, traceback

PARAMS = [
${params.map(([n, e, u, c]) => `    (${py(n)}, ${py(e)}, ${py(u)}, ${py(c)}),`).join('\n')}
]
SHAFTS = [
${s.shafts.map((sh) => `    (${py(sh.id)}, ${num(sh.x)}, ${num(sh.y)}),`).join('\n')}
]
LINKS = [
${links.map(([a, b]) => `    (${py(a)}, ${py(b)}),`).join('\n')}
]
SKETCH_NAME = "GearTrain Layout"
ATTR_GROUP = "GearGoober"


def run(context):
    ui = None
    try:
        app = adsk.core.Application.get()
        ui = app.userInterface
        design = adsk.fusion.Design.cast(app.activeProduct)
        if not design:
            ui.messageBox("Open a design before running this script.")
            return

        params = design.userParameters
        created = updated = 0
        for name, expr, units, comment in PARAMS:
            existing = params.itemByName(name)
            if existing:
                existing.expression = expr
                existing.comment = comment
                updated += 1
            else:
                params.add(name, adsk.core.ValueInput.createByString(expr), units, comment)
                created += 1

        root = design.rootComponent
        sketch = root.sketches.itemByName(SKETCH_NAME)
        if not sketch:
            sketch = root.sketches.add(root.xYConstructionPlane)
            sketch.name = SKETCH_NAME

        points = {}
        for pt in sketch.sketchPoints:
            attr = pt.attributes.itemByName(ATTR_GROUP, "shaft")
            if attr:
                points[attr.value] = pt
        for sid, x_mm, y_mm in SHAFTS:
            target = adsk.core.Point3D.create(x_mm / 10.0, y_mm / 10.0, 0)  # Fusion API lengths are cm
            pt = points.get(sid)
            if pt:
                g = pt.geometry
                pt.move(adsk.core.Vector3D.create(target.x - g.x, target.y - g.y, 0))
            else:
                pt = sketch.sketchPoints.add(target)
                pt.attributes.add(ATTR_GROUP, "shaft", sid)
                points[sid] = pt

        linked = set()
        for line in sketch.sketchCurves.sketchLines:
            attr = line.attributes.itemByName(ATTR_GROUP, "link")
            if attr:
                linked.add(attr.value)
        for a, b in LINKS:
            key = a + "|" + b
            if key in linked:
                continue
            line = sketch.sketchCurves.sketchLines.addByTwoPoints(points[a], points[b])
            line.isConstruction = True
            line.attributes.add(ATTR_GROUP, "link", key)

        ui.messageBox(
            "GearGoober: %d parameters created, %d updated.\\nSketch '%s' has %d shaft points."
            % (created, updated, SKETCH_NAME, len(SHAFTS))
        )
    except:
        if ui:
            ui.messageBox("GearGoober script failed:\\n" + traceback.format_exc())
`;
}
