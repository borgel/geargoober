"""Generate src/core/export/dxfTemplate.ts: a valid, empty AC1015 (R2000) DXF skeleton.

Run with: ./gg run python3 tools/make_dxf_template.py
The skeleton defines GearGoober's layers and linetypes; the TypeScript writer inserts
entities into the ENTITIES section and patches $HANDSEED.
"""
import io
import json

import ezdxf

LAYERS = [
    # name, ACI color, linetype
    ("PROFILE", 7, "Continuous"),
    ("BORE", 1, "Continuous"),
    ("PITCH_CIRCLE", 8, "DASHED"),
    ("CENTER", 3, "Continuous"),
    ("SHAFTS", 3, "Continuous"),
    ("DIMENSIONS", 5, "Continuous"),
    ("LABELS", 4, "Continuous"),
]

doc = ezdxf.new("R2000", setup=False)
doc.units = 4  # millimetres
doc.header["$MEASUREMENT"] = 1
doc.header["$INSUNITS"] = 4
doc.linetypes.add("DASHED", pattern=[1.5, 1.0, -0.5], description="Dashed __ __ __")
for name, color, lt in LAYERS:
    doc.layers.add(name, color=color, linetype=lt)

buf = io.StringIO()
doc.write(buf)
text = buf.getvalue().replace("\r\n", "\n")

msp_handle = doc.modelspace().block_record.dxf.handle
seed = int(doc.entitydb.handles.next(), 16)  # first free handle
lines = text.split("\n")
# patch $HANDSEED value with a placeholder
for i, line in enumerate(lines):
    if line.strip() == "$HANDSEED":
        lines[i + 2] = "{{HANDSEED}}"
        break
text = "\n".join(lines)
marker = "0\nSECTION\n  2\nENTITIES\n" if "  2\nENTITIES" in text else "0\nSECTION\n2\nENTITIES\n"
idx = text.index("ENTITIES\n") + len("ENTITIES\n")
head, rest = text[:idx], text[idx:]
end = rest.index("ENDSEC")
# rest starts with existing (empty) entities; back up to the group code line before ENDSEC
tail_start = rest.rfind("\n", 0, rest.rfind("\n", 0, end)) + 1 if end > 0 else 0
tail = rest[tail_start:]

out = f"""// Generated by tools/make_dxf_template.py (ezdxf {ezdxf.__version__}). Do not edit by hand.
export const DXF_HEAD = {json.dumps(head)};
export const DXF_TAIL = {json.dumps(tail)};
export const MODEL_SPACE_HANDLE = {json.dumps(msp_handle)};
export const FIRST_FREE_HANDLE = {seed};
"""
open("src/core/export/dxfTemplate.ts", "w").write(out)
print("ok", len(head), len(tail), msp_handle, hex(seed))
